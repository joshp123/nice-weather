// Prepare antialiased Barlow glyphs for the dependency-free Worker PNG renderer.
package main

import (
	"bytes"
	"compress/gzip"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"image"
	"image/draw"
	"math"
	"os"

	"golang.org/x/image/font"
	"golang.org/x/image/font/opentype"
	"golang.org/x/image/math/fixed"
)

type glyph struct { X, Y, Width, Height, Left, Top int; Advance float64 }

func main() {
	const width, height, size = 2048, 8192, 128
	atlas := image.NewAlpha(image.Rect(0, 0, width, height))
	fonts := map[string]map[string]glyph{}
	x, y, rowHeight := 1, 1, 0
	for _, weight := range []string{"Regular", "Bold"} {
		body, err := os.ReadFile("outlook/assets/Barlow-" + weight + ".ttf"); if err != nil { panic(err) }
		parsed, err := opentype.Parse(body); if err != nil { panic(err) }
		face, err := opentype.NewFace(parsed, &opentype.FaceOptions{Size:size, DPI:72, Hinting:font.HintingNone}); if err != nil { panic(err) }
		glyphs := map[string]glyph{}
		for r := rune(32); r <= 0x024f; r++ {
			if r >= 127 && r < 160 { continue }
			bounds, advance, ok := face.GlyphBounds(r); if !ok { continue }
			left, top := int(math.Floor(float64(bounds.Min.X)/64)), int(math.Floor(float64(bounds.Min.Y)/64))
			w, h := int(math.Ceil(float64(bounds.Max.X)/64))-left, int(math.Ceil(float64(bounds.Max.Y)/64))-top
			if x+w+1 >= width { x=1; y+=rowHeight+2; rowHeight=0 }
			if y+h+1 >= height { panic("font atlas exceeded its canvas") }
			g := glyph{X:x,Y:y,Width:w,Height:h,Left:left,Top:top,Advance:float64(advance)/64}
			glyphs[string(r)] = g
			drawer := font.Drawer{Dst:atlas,Src:image.White,Face:face,Dot:fixed.P(x-left,y-top)}; drawer.DrawString(string(r))
			x+=w+2; if h>rowHeight { rowHeight=h }
		}
		face.Close(); fonts[weight]=glyphs
	}
	usedHeight:=y+rowHeight+1
	mask:=image.NewAlpha(image.Rect(0,0,width,usedHeight)); draw.Draw(mask,mask.Bounds(),atlas,image.Point{},draw.Src)
	var packed bytes.Buffer; compressor:=gzip.NewWriter(&packed); if _,err:=compressor.Write(mask.Pix);err!=nil{panic(err)};if err:=compressor.Close();err!=nil{panic(err)}
	metadata,_:=json.Marshal(map[string]any{"size":size,"width":width,"height":usedHeight,"fonts":fonts})
	license,err:=os.ReadFile("outlook/assets/OFL.txt");if err!=nil{panic(err)}
	output:=fmt.Sprintf("// Written by AI on 2026.10.18 by model GPT-6.1 Sol. Generated by research/fine/preview-font.\n/*\n%s\n*/\nexport const previewFontMetadata=%s;\nexport const previewFontMask='%s';\n",license,metadata,base64.StdEncoding.EncodeToString(packed.Bytes()))
	if err:=os.WriteFile("hosting/sites/fine-preview-font.mjs",[]byte(output),0644);err!=nil{panic(err)}
	fmt.Printf("Barlow Worker atlas: %dx%d alpha, %d gzip bytes, %d source bytes\n",width,usedHeight,packed.Len(),len(output))
}
